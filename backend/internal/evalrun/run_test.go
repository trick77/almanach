// gitRepo makes a one-commit repository with files under dir.
func gitRepo(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for p, body := range files {
		full := filepath.Join(dir, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	for _, args := range [][]string{
		{"init", "-q", "-b", "main"}, {"add", "-A"},
		{"-c", "user.name=t", "-c", "user.email=t@localhost", "commit", "-q", "-m", "c"},
	} {
		if out, err := exec.Command("git", append([]string{"-C", dir}, args...)...).CombinedOutput(); err != nil { //nolint:gosec // test fixture
			t.Fatalf("git %v: %v %s", args, err, out)
		}
	}
}

// A run over a one-repository folder against a fake model: the repository
// is registered, cloned, queued and run by the real worker, and the report
// names it, labelled, with its calls counted.
func TestRunEndToEndAgainstAFakeModel(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not on PATH")
	}
	dir := t.TempDir()
	gitRepo(t, filepath.Join(dir, "projects", "p1", "r1"), map[string]string{
		"README.md": "# r1\n", "main.go": "package main\n\nfunc main() {}\n", "main_test.go": "package main\n",
	})
	if err := os.MkdirAll(filepath.Join(dir, "labels", "p1"), 0o750); err != nil {
		t.Fatal(err)
	}
	labels := "repo: r1\nmust_read:\n  - path: main.go\n    why: entry\nnever_read:\n  - glob: \"**/*_test.go\"\n    why: tests\nquestions:\n  - id: q1\n    category: domain\n    q: Was?\n    answer: Nichts.\n    evidence: [main.go]\n"
	if err := os.WriteFile(filepath.Join(dir, "labels", "p1", "r1.yaml"), []byte(labels), 0o600); err != nil {
		t.Fatal(err)
	}
	srv := llmwiretest.NewServer(t)
	srv.SetReply(`{"subjects": [{"name": "Kern", "purpose": "Der Kern.", "paths": ["main.go"]}]}`)
	// A real profile, routed to the fake through the LiteLLM variables
	// under the alias the fake lists.
	env := map[string]string{"LLMWIRE_LITELLM_BASE_URL": srv.URL, "LLMWIRE_LITELLM_API_KEY": "k", "LLMWIRE_LITELLM_MODELS": "mimo-v2.6-pro=" + llmwiretest.ChatModel}
	lookup := func(k string) (string, bool) { v, ok := env[k]; return v, ok }
	log := slog.New(slog.NewTextHandler(io.Discard, nil))
	const model = "mimo-v2.6-pro"
	rep, err := Run(context.Background(), Options{Dir: dir, Out: filepath.Join(dir, "out"), Model: model, Judge: model,
		Lookup: lookup, Deadline: 30 * time.Second, Split: true, Log: log})
	if err != nil {
		t.Fatal(err)
	}
	if len(rep.Projects) != 1 || len(rep.Projects[0].Repos) != 1 {
		t.Fatalf("report = %+v", rep)
	}
	r := rep.Projects[0].Repos[0]
	if !r.Labelled || r.Calls == 0 || r.RunState == "" {
		t.Errorf("repo report = %+v, want labelled, calls made, a run state", r)
	}
	if strings.Contains(strings.Join(r.NoiseFiles, ","), "main_test.go") {
		t.Errorf("the test file was read: %v", r.NoiseFiles)
	}
	if md := rep.Markdown(); !strings.Contains(md, "## p1") || !strings.Contains(md, "| r1 |") {
		t.Errorf("markdown = %q", md)
	}
	// The same folder again: the project refused, a run is there.
	again, err := Run(context.Background(), Options{Dir: dir, Out: filepath.Join(dir, "out"), Model: model, Judge: model,
		Lookup: lookup, Deadline: time.Second, Split: true, Log: log})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(again.Projects[0].Error, "holds a run already") {
		t.Errorf("second run into the same folder: %q, want refused", again.Projects[0].Error)
	}
}

// What the reader drops at read time is no file read: a generator's output
// by its head, a Secret manifest. A path git cannot show stays counted.
func TestUnreadLeavesOutWhatTheReaderDrops(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not on PATH")
	}
	dir := t.TempDir()
	gitRepo(t, dir, map[string]string{
		"a.go":        "package a\n",
		"client.go":   "// Code generated by apigen. DO NOT EDIT.\npackage a\n",
		"secret.yaml": "apiVersion: v1\nkind: Secret\ndata:\n  x: eQ==\n",
	})
	sha, err := exec.Command("git", "-C", dir, "rev-parse", "HEAD").Output()
	if err != nil {
		t.Fatal(err)
	}
	picked := map[string]int64{"a.go": 1, "client.go": 2, "secret.yaml": 3, "gone.go": 4}
	unread(context.Background(), dir, strings.TrimSpace(string(sha)), picked)
	if len(picked) != 2 || picked["a.go"] != 1 || picked["gone.go"] != 4 {
		t.Errorf("picked = %v, want a.go and gone.go", picked)
	}
	unread(context.Background(), dir, "", picked)
	if len(picked) != 2 {
		t.Errorf("no commit: picked changed to %v", picked)
	}
}

// The judge's verdicts are scored; a reply off the schema is an error.
func TestJudgeScoresThePage(t *testing.T) {
	srv := llmwiretest.NewServer(t)
	srv.SetReply(`{"answers": [{"id": "q1", "verdict": "answered", "note": "ok"}, {"id": "q2", "verdict": "partial", "note": "half"}]}`)
	j := &judge{wire: srv.Client(), model: llmwiretest.ChatModel}
	qs := []Question{{ID: "q1", Category: "domain", Q: "a?", Answer: "a"}, {ID: "q2", Category: "build", Q: "b?", Answer: "b"}}
	ans, _, err := j.ask(context.Background(), "page", qs)
	if err != nil {
		t.Fatal(err)
	}
	if got := coverage(ans, len(qs)); got != 0.75 {
		t.Errorf("coverage = %v, want 0.75", got)
	}
	if ans[1].Category != "build" {
		t.Errorf("category not carried: %+v", ans[1])
	}
	// An id renamed, the count kept: by position. One left out: missing.
	srv.SetReply(`{"answers": [{"id": "", "verdict": "answered", "note": "a"}, {"id": "q1", "verdict": "answered", "note": "b"}]}`)
	if ans, _, _ = j.ask(context.Background(), "page", qs); ans[0].ID != "q1" || ans[1].ID != "q2" || ans[0].Note != "b" {
		t.Errorf("renamed id: %+v", ans)
	}
	srv.SetReply(`{"answers": [{"id": "q2", "verdict": "answered", "note": "b"}, {"id": "q9", "verdict": "answered", "note": "x"}, {"id": "q8", "verdict": "answered", "note": "y"}]}`)
	if ans, _, _ = j.ask(context.Background(), "page", qs); len(ans) != 2 || ans[0].Verdict != "missing" || coverage(ans, 2) != 0.5 {
		t.Errorf("left out: %+v", ans)
	}
	srv.SetReply("not json")
	if _, _, err := j.ask(context.Background(), "page", qs); err == nil {
		t.Error("an answer off the schema: want an error")
	}
}

// Two runs average per repository, each run's coverage kept beside the
// mean, and the totals count both runs.
func TestMeansOverRuns(t *testing.T) {
	run := func(cov, cost float64, chars int) []ProjectReport {
		return []ProjectReport{{Key: "p", Repos: []RepoReport{{Slug: "a", Coverage: cov, MustReadRecall: cov, CostUSD: cost, Calls: 4,
			NoiseBytes: 2000, ReadBytes: 4000, Page: &PageStats{Chars: chars}, Outcomes: map[string]int{"too_long": 1}}}}}
	}
	rep := &Report{Repeat: 2, Runs: [][]ProjectReport{run(0.5, 1, 100), run(1, 3, 300)}}
	rep.Projects = rep.Runs[0]
	rep.Means = means(rep.Runs)
	rep.total()
	if len(rep.Means) != 1 {
		t.Fatalf("means = %+v", rep.Means)
	}
	m := rep.Means[0]
	if m.Coverage != 0.75 || m.CostUSD != 2 || m.Chars != 200 || m.Calls != 4 || len(m.Coverages) != 2 || m.Runs != 2 {
		t.Errorf("mean = %+v", m)
	}
	if rep.Calls != 8 || rep.CostUSD != 4 || rep.CutAnswers != 2 {
		t.Errorf("totals = %d calls, $%v, %d cut; want both runs counted", rep.Calls, rep.CostUSD, rep.CutAnswers)
	}
	md := rep.Markdown()
	for _, want := range []string{"## Means over 2 runs", "| p | a | 75% (50, 100) |", "# Run 1", "# Run 2"} {
		if !strings.Contains(md, want) {
			t.Errorf("markdown lacks %q:\n%s", want, md)
		}
	}
	if means(nil) != nil {
		t.Error("means of no run: want nil")
	}
}

// The code-read topics are held to the labels' by name and way: found,
// missed, or beyond them; no labels, no score.
func TestTopicScore(t *testing.T) {
	var rep RepoReport
	topicScore(&rep, []TopicLabel{{Name: "a", Direction: "produces"}, {Name: "b", Direction: "consumes"}},
		[]messaging.Topic{{Name: "a", Direction: "produces"}, {Name: "b", Direction: "produces"}})
	if rep.TopicRecall == nil || *rep.TopicRecall != 0.5 || !reflect.DeepEqual(rep.TopicsMissed, []string{"b consumes"}) ||
		!reflect.DeepEqual(rep.TopicsExtra, []string{"b produces"}) {
		t.Errorf("rep = %+v", rep)
	}
	rep = RepoReport{Labelled: true}
	topicScore(&rep, nil, []messaging.Topic{{Name: "a", Direction: "produces"}})
	if rep.TopicRecall != nil {
		t.Error("no topic labels: want no score")
	}
	half := 0.5
	r := &Report{Projects: []ProjectReport{{Key: "p", Repos: []RepoReport{{Slug: "a", Labelled: true, TopicRecall: &half,
		TopicsMissed: []string{"b consumes"}, TopicsExtra: []string{"c produces"}}}}}}
	if md := r.Markdown(); !strings.Contains(md, "topics found: 50%; missed: b consumes; beyond the labels: c produces") {
		t.Errorf("markdown = %s", md)
	}
}

// The code-read interfaces are held to the labels' by kind, name and way,
// the offered operations by method and path, parameters by position: a
// partner's spec read as offered is missed and extra both, a path set
// together wrong is too.
func TestInterfaceScore(t *testing.T) {
	read := endpoints.Read{
		APIs: []endpoints.API{
			{Kind: "http", Name: "Orders", Direction: "offers"},
			{Kind: "http", Name: "Partner", Direction: "offers"},
			{Kind: "http", Name: "", Direction: "offers"},
		},
		Endpoints: []endpoints.Endpoint{
			{Kind: "http", API: "Orders", Method: "GET", Path: "/v1/orders/{orderId}", Direction: "offers"},
			{Kind: "http", API: "", Method: "*", Path: "/health", Direction: "offers"},
			{Kind: "http", API: "", Method: "GET", Path: "/items", Direction: "offers"},
			{Kind: "http", API: "Partner", Method: "GET", Path: "/p", Direction: "declares"},
		},
	}
	var rep RepoReport
	// The name any case; a label twice counts once.
	interfaceScore(&rep,
		&[]InterfaceLabel{{Kind: "http", Name: "orders", Direction: "offers"}, {Kind: "http", Name: "Partner", Direction: "declares"}},
		&[]EndpointLabel{{Kind: "http", Method: "GET", Path: "/v1/orders/:id"}, {Kind: "http", Method: "GET", Path: "/v1/orders/{x}"},
			{Kind: "http", Method: "*", Path: "/health"}, {Kind: "http", Method: "GET", Path: "/v1/items"}},
		read, true)
	if rep.InterfaceRecall == nil || *rep.InterfaceRecall != 0.5 ||
		!reflect.DeepEqual(rep.InterfacesMissed, []string{`http "Partner" declares`}) ||
		!reflect.DeepEqual(rep.InterfacesExtra, []string{`http "Partner" offers`, `http "" offers`}) {
		t.Errorf("interfaces: %v %q %q", deref(rep.InterfaceRecall), rep.InterfacesMissed, rep.InterfacesExtra)
	}
	if rep.EndpointRecall == nil || *rep.EndpointRecall < 0.66 || *rep.EndpointRecall > 0.67 ||
		!reflect.DeepEqual(rep.EndpointsMissed, []string{"http GET /v1/items"}) ||
		!reflect.DeepEqual(rep.EndpointsExtra, []string{"http GET /items"}) {
		t.Errorf("endpoints: %v %q %q", deref(rep.EndpointRecall), rep.EndpointsMissed, rep.EndpointsExtra)
	}
	var none RepoReport
	interfaceScore(&none, nil, nil, read, true)
	if none.InterfaceRecall != nil || none.EndpointRecall != nil {
		t.Error("no labels: want no score")
	}
	// Labelled as offering none: what was read is all beyond the labels.
	var lib RepoReport
	interfaceScore(&lib, nil, &[]EndpointLabel{}, read, true)
	if lib.EndpointRecall == nil || *lib.EndpointRecall != 1 || len(lib.EndpointsExtra) != 3 || lib.InterfaceRecall != nil {
		t.Errorf("labelled none: %v %q", deref(lib.EndpointRecall), lib.EndpointsExtra)
	}
	// Never read: not scored, said so, no 0%.
	var unread RepoReport
	interfaceScore(&unread, &[]InterfaceLabel{{Kind: "http", Name: "Orders", Direction: "offers"}}, nil, endpoints.Read{}, false)
	if !unread.InterfacesNotRead || unread.InterfaceRecall != nil {
		t.Errorf("never read: %+v", unread)
	}
	// A label the reader can never match is the label file's fault, said
	// at load; kind and method any case.
	ok := Labels{Endpoints: &[]EndpointLabel{{Kind: "HTTP", Method: "get", Path: "/x"}}}
	if err := ok.check(); err != nil || (*ok.Endpoints)[0].Kind != "http" || (*ok.Endpoints)[0].Method != "GET" {
		t.Errorf("check: %v %+v", err, *ok.Endpoints)
	}
	for _, bad := range []Labels{
		{Interfaces: &[]InterfaceLabel{{Kind: "http", Name: "X", Direction: "offer"}}},
		{Endpoints: &[]EndpointLabel{{Method: "GET", Path: "/x"}}},
		{Endpoints: &[]EndpointLabel{{Kind: "http", Path: "/x"}}},
	} {
		if bad.check() == nil {
			t.Errorf("check passed %+v", bad)
		}
	}
	half := 0.5
	r := &Report{Projects: []ProjectReport{{Key: "p", Repos: []RepoReport{{Slug: "a", Labelled: true, InterfaceRecall: &half,
		InterfacesMissed: []string{`http "Partner" declares`}, EndpointRecall: &half, EndpointsExtra: []string{"http GET /items"}}}}}}
	md := r.Markdown()
	if !strings.Contains(md, `interfaces found: 50%; missed: http "Partner" declares`+"\n") ||
		!strings.Contains(md, "endpoints found: 50%; beyond the labels: http GET /items\n") ||
		!strings.Contains((&Report{Projects: []ProjectReport{{Key: "p", Repos: []RepoReport{{Slug: "a", Labelled: true,
			InterfacesNotRead: true}}}}}).Markdown(), "interfaces not read from the code: not scored") {
		t.Errorf("markdown: %s", md)
	}
}

func deref(f *float64) any {
	if f == nil {
		return nil
	}
	return *f
}

func TestScoreAndMarkdown(t *testing.T) {
	srv := llmwiretest.NewServer(t)
	srv.SetReply(`{"answers": [{"id": "q1", "verdict": "missing", "note": "nothing"}]}`)
	j := &judge{wire: srv.Client(), model: llmwiretest.ChatModel}
	cost := int64(2_000_000)
	start, end := time.Now(), time.Now().Add(time.Minute)
	p := Project{Key: "p", Repos: []Repo{
		{Slug: "a", Labels: &Labels{MustRead: []MustRead{{Path: "x.go"}, {Path: "y.go"}}, NeverRead: []Glob{{Glob: "z/**"}},
			Questions: []Question{{ID: "q1", Category: "data", Q: "?", Answer: "!"}}}},
		{Slug: "b"},
	}}
	res := ProjectResult{Key: "p", TimedOut: true, Repos: map[string]RepoResult{
		"a": {Run: store.BaselineRun{State: "done", Error: "", StartedAt: &start, FinishedAt: &end},
			Calls:  []store.RunCall{{Outcome: "ok", CostNanoUSD: &cost}, {Outcome: "too_long"}},
			Page:   &store.Page{Summary: "Er sollte.", Statements: []store.Statement{{Kind: "rule", Name: "n", Text: "t", Files: []string{"y.go"}}}},
			Picked: map[string]int64{"x.go": 1, "z/n.bin": 3000}},
	}, ProjectPage: &store.Page{Shape: "system"}}
	pr := score(context.Background(), p, res, j, slog.New(slog.NewTextHandler(io.Discard, nil)))
	rep := &Report{Projects: []ProjectReport{pr}}
	rep.total()
	a := pr.Repos[0]
	if a.Calls != 2 || a.Unpriced != 1 || a.CostUSD != 0.002 || a.MustReadRecall != 0.5 || a.NoiseBytes != 3000 || a.Coverage != 0 || len(a.Rules) != 1 {
		t.Errorf("repo a = %+v", a)
	}
	if rep.CutAnswers != 1 || rep.Calls != 2 {
		t.Errorf("totals: %+v", rep)
	}
	md := rep.Markdown()
	for _, want := range []string{"deadline reached", "shape system", "q1 (data): **missing**", "must-read not read: y.go", "noise read (1 files)"} {
		if !strings.Contains(md, want) {
			t.Errorf("markdown lacks %q:\n%s", want, md)
		}
	}
}
